KELAS = list(DATA.keys())


def semua():
    """Iterator: (kelas, nis, nama, jk)"""
    for kelas in KELAS:
        for nis, nama, jk in DATA[kelas]:
            yield kelas, nis, nama, jk


def rekap():
    out = []
    for kelas in KELAS:
        rows = DATA[kelas]
        l = sum(1 for _, _, jk in rows if jk == "L")
        p = sum(1 for _, _, jk in rows if jk == "P")
        out.append({"kelas": kelas, "jumlah": len(rows), "l": l, "p": p})
    return out


